// Command report runs the micro-benchmarks, the accuracy simulation and an
// in-process HTTP load test, then writes the results as Markdown.
//
//	go run ./bench/cmd/report -out bench/RESULTS.md
package main

import (
	"bufio"
	"context"
	"flag"
	"fmt"
	"io"
	"log/slog"
	"net"
	"net/http"
	"os"
	"runtime"
	"sort"
	"strings"
	"testing"
	"time"

	"github.com/alicebob/miniredis/v2"

	"github.com/HappyVirgo/edge-limiter/bench"
	"github.com/HappyVirgo/edge-limiter/bench/load"
	"github.com/HappyVirgo/edge-limiter/internal/config"
	"github.com/HappyVirgo/edge-limiter/internal/metrics"
	"github.com/HappyVirgo/edge-limiter/internal/server"
)

func main() {
	testing.Init()
	out := flag.String("out", "bench/RESULTS.md", "markdown output path")
	loadDur := flag.Duration("load-duration", 5*time.Second, "duration of each HTTP load run")
	conc := flag.Int("c", 64, "HTTP load concurrency")
	cpu := flag.String("cpu", cpuModel(), "CPU description to record (auto-detected on Linux)")
	runs := flag.Int("runs", 3, "repetitions per measurement; the median is reported")
	flag.Parse()

	var md strings.Builder
	w := io.MultiWriter(&md, os.Stdout)
	fmt.Fprintf(w, "# edge-limiter benchmark results\n\n")
	fmt.Fprintf(w, "Generated by `go run ./bench/cmd/report` on %s.\n\n", time.Now().Format("2006-01-02"))
	fmt.Fprintf(w, "- Machine: %s, %d logical CPUs, %s/%s\n- Go: %s\n\n", *cpu, runtime.NumCPU(), runtime.GOOS, runtime.GOARCH, runtime.Version())
	fmt.Fprintf(w, "`miniredis` is an in-process Redis emulator: those rows exercise the real Lua scripts and go-redis\n"+
		"client, but their latency reflects the emulator (which re-creates a Lua VM per script call), not a real Redis server.\n\n")

	microBenchmarks(w, *runs)
	accuracy(w)
	httpLoad(w, *conc, *loadDur, *runs)

	if err := os.WriteFile(*out, []byte(md.String()), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func microBenchmarks(w io.Writer, runs int) {
	fmt.Fprintf(w, "## Backend micro-benchmarks\n\n")
	fmt.Fprintf(w, "`Allow` called from %d parallel goroutines over 1,024 keys (same code as\n`go test -bench . ./bench`); median of %d runs.\n\n", runtime.GOMAXPROCS(0), runs)
	fmt.Fprintf(w, "| backend | algorithm | ns/op | checks/sec | allocs/op |\n|---|---|---:|---:|---:|\n")
	for _, f := range bench.Factories {
		for _, l := range bench.Limits {
			r := median(runs, func() testing.BenchmarkResult { return testing.Benchmark(bench.AllowBenchmark(f, l)) },
				func(r testing.BenchmarkResult) float64 { return float64(r.NsPerOp()) })
			ns := float64(r.T.Nanoseconds()) / float64(r.N)
			fmt.Fprintf(w, "| %s | %s | %.0f | %s | %d |\n", f.Name, l.Algorithm, ns, thousands(1e9/ns), r.AllocsPerOp())
		}
	}
	fmt.Fprintln(w)
}

func accuracy(w io.Writer) {
	const dur = 60 * time.Second
	arrivals := bench.BurstyTraffic(42, dur, 60, 400, 3*time.Second)
	fmt.Fprintf(w, "## Accuracy under bursty traffic\n\n")
	fmt.Fprintf(w, "Synthetic traffic for one key (seed 42): %.0fs of Poisson background at 60 req/s plus bursts of 400 requests\n"+
		"within 200 ms arriving every ~3 s on average; %d requests total (%.0f req/s offered). Limit: 100 per 1 s\n"+
		"(token bucket burst = 100). Simulated on a manual clock, so the results are deterministic.\n\n", dur.Seconds(), len(arrivals), float64(len(arrivals))/dur.Seconds())
	fmt.Fprintf(w, "| algorithm | allowed | mean allowed/s | max in any 1 s window | vs limit | memory == miniredis |\n|---|---:|---:|---:|---:|---|\n")
	for _, l := range bench.Limits {
		mem := bench.Accuracy(bench.Factories[0], l, arrivals, dur)
		red := bench.Accuracy(bench.Factories[1], l, arrivals, dur)
		fmt.Fprintf(w, "| %s | %d | %.1f | %d | %+.0f%% | %v |\n", l.Algorithm, mem.Allowed, mem.AllowedPerPeriod,
			mem.MaxInWindow, 100*(float64(mem.MaxInWindow)/float64(l.Rate)-1), mem == red)
	}
	fmt.Fprintln(w)
}

func httpLoad(w io.Writer, conc int, dur time.Duration, runs int) {
	mr, err := miniredis.Run()
	if err != nil {
		panic(err)
	}
	defer mr.Close()
	fmt.Fprintf(w, "## HTTP load test\n\n")
	fmt.Fprintf(w, "`bench/load` driving `POST /v1/check` on an in-process server over loopback TCP: %d workers, %s per run,\n"+
		"10,000 random keys, default rule (token bucket, 100/s, burst 200). Client and server share the machine;\nmedian of %d runs by throughput.\n\n", conc, dur, runs)
	fmt.Fprintf(w, "| backend | checks/sec | p50 | p95 | p99 | max | errors |\n|---|---:|---:|---:|---:|---:|---:|\n")
	for _, c := range []struct{ name, doc string }{
		{"memory", "backend: {type: memory}"},
		{"miniredis", fmt.Sprintf("backend: {type: redis, redis: {addr: '%s', timeout: 1s}}", mr.Addr())},
	} {
		cfg, err := config.Parse([]byte(c.doc+"\ndefault: {algorithm: token_bucket, rate: 100, period: 1s, burst: 200}"), func(string) string { return "" })
		if err != nil {
			panic(err)
		}
		r := median(runs, func() load.Result { return runServer(cfg, conc, dur) }, load.Result.ChecksPerSec)
		fmt.Fprintf(w, "| %s | %s | %s | %s | %s | %s | %d |\n", c.name, thousands(r.ChecksPerSec()),
			ms(r.P50), ms(r.P95), ms(r.P99), ms(r.Max), r.Errors)
	}
	fmt.Fprintln(w)
}

func runServer(cfg *config.Config, conc int, dur time.Duration) load.Result {
	log := slog.New(slog.NewJSONHandler(io.Discard, nil))
	m := metrics.New()
	backend, closer := server.BuildBackend(cfg, m, log)
	defer closer.Close()
	ln, err := net.Listen("tcp", "127.0.0.1:0")
	if err != nil {
		panic(err)
	}
	srv := &http.Server{Handler: server.New(cfg, backend, m, log).Handler(), ReadHeaderTimeout: 5 * time.Second}
	go func() { _ = srv.Serve(ln) }()
	defer srv.Close()
	return load.Run(context.Background(), load.Options{URL: "http://" + ln.Addr().String(), Concurrency: conc, Duration: dur, Keys: 10000})
}

func ms(d time.Duration) string { return fmt.Sprintf("%.2f ms", float64(d.Microseconds())/1000) }

func thousands(v float64) string {
	s := fmt.Sprintf("%.0f", v)
	for i := len(s) - 3; i > 0; i -= 3 {
		s = s[:i] + "," + s[i:]
	}
	return s
}

// cpuModel reads the CPU model name from the OS where that is cheap.
func cpuModel() string {
	if v := os.Getenv("PROCESSOR_IDENTIFIER"); runtime.GOOS == "windows" && v != "" {
		return v
	}
	if f, err := os.Open("/proc/cpuinfo"); err == nil {
		defer f.Close()
		s := bufio.NewScanner(f)
		for s.Scan() {
			if k, v, ok := strings.Cut(s.Text(), ":"); ok && strings.TrimSpace(k) == "model name" {
				return strings.TrimSpace(v)
			}
		}
	}
	return "unknown CPU"
}

// median runs measure n times and returns the run with the median score.
func median[T any](n int, measure func() T, score func(T) float64) T {
	rs := make([]T, n)
	for i := range rs {
		rs[i] = measure()
	}
	sort.Slice(rs, func(i, j int) bool { return score(rs[i]) < score(rs[j]) })
	return rs[n/2]
}
